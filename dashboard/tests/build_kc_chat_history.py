def when(value):
    """«DD.MM HH:MM» (или «~DD.MM HH:MM» — по времени сообщения) → (ISO, точное?)."""
    if not value:
        return None, False
    exact = not value.startswith("~")
    day, hm = value.lstrip("~").split()
    d, m = map(int, day.split("."))
    h, mi = map(int, hm.split(":"))
    return datetime(YEAR, m, d, h, mi, tzinfo=TZ).isoformat(), exact


def build():
    ops, seen = [], set()
    for msgs, product, operation, start, end, people, qty, unit, plan, note, flag in R:
        ids = msgs.split(",")
        key = f"tg-{ids[0]}-{len([o for o in ops if o['msgs'][0] == ids[0]])}"
        assert key not in seen
        seen.add(key)
        start_at, start_exact = when(start)
        end_at, end_exact = when(end)
        if start_at and end_at:
            assert end_at >= start_at, (msgs, start, end)
        ops.append({
            "id": key, "msgs": ids, "product": product, "operation": operation, "people": people,
            "qty": qty, "unit": unit, "plan": plan, "start_at": start_at, "start_exact": start_exact,
            "end_at": end_at, "end_exact": end_exact, "status": "closed" if end_at else "open",
            "flag": flag or "ok", "note": note,
        })
    handoffs = []
    for product, at, qty, msg in HANDOFFS:
        iso, exact = when(at)
        handoffs.append({"product": product, "at": iso, "exact": exact, "qty": qty, "unit": "шт", "msgs": [msg]})
    return {"source": CHAT, "parsed_by": "ручной разбор, номера сообщений в msgs", "operations": ops, "handoffs": handoffs}


